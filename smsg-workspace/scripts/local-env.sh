#!/usr/bin/env bash
# Regenerates api/.env.development.local and web/.env.development.local
# from the running local Supabase (ADR-032). Never prints values.
set -euo pipefail

status=$(cd api && supabase status -o env)

get() { # first matching variable name wins; strips surrounding quotes
  local name
  for name in "$@"; do
    local line
    line=$(grep -E "^${name}=" <<<"$status" | head -n1 || true)
    if [[ -n $line ]]; then
      local value=${line#*=}
      value=${value%\"}; value=${value#\"}
      printf '%s' "$value"
      return
    fi
  done
  echo "local-env: missing ${*} in 'supabase status -o env'" >&2
  exit 1
}

supabase_url=$(get API_URL)
db_url=$(get DB_URL)
publishable_key=$(get PUBLISHABLE_KEY ANON_KEY)
secret_key=$(get SECRET_KEY SERVICE_ROLE_KEY)

umask 077
cat >api/.env.development.local <<EOF
# Generated by 'make dev' from local Supabase. Do not edit: edit .env.local instead.
SUPABASE_URL=${supabase_url}
DATABASE_URL=${db_url}
SUPABASE_SECRET_KEY=${secret_key}
EOF

cat >web/.env.development.local <<EOF
# Generated by 'make dev' from local Supabase. Do not edit: edit .env.local instead.
NEXT_PUBLIC_SUPABASE_URL=${supabase_url}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishable_key}
EOF

chmod 600 api/.env.development.local web/.env.development.local # umask skips existing files

echo "local-env: wrote api/.env.development.local and web/.env.development.local"
